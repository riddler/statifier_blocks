defmodule StatifierBlocks.MapFixtures do
  @moduledoc """
  The two teaching documents the Map is read against - a library loan and a
  patron registration, one library world - and the words a host of that
  world has for its event names.

  The documents are copies of the reference host's
  (`statifier_examples@c620756`, `priv/fixtures/`), written from `core.*`
  blocks alone, under `test/fixtures/documents/statifier_examples_c620756/`.
  The graphs under `test/fixtures/map/` are what the reference host's own
  map module answered for them at that commit, with the phrase table below
  standing in for the host's: generated by compiling that module against
  this package, never written by hand, so `StatifierBlocks.MapTest` holding
  the package's graph equal to them is the claim that the Map moved without
  changing what it answers.

  Since then the package's own `StatifierBlocks.Map` is the owner, and a
  change to what it answers regenerates a graph from it, never by hand:
  the library loan's graph was regenerated when a timed wait gained the
  clock mark, both graphs when the start dot moved out of the root's box
  to stand first in the graph, above it, both again when the start dot
  gained the word Start and every end mark the word End, the library
  loan's again when a wrapped arm entry's later lines gained their
  indent, both again when the graph gained its key, both again when the
  start edge's caption came to name who starts the document, and both
  again when a group's rules column gained its own caption and its type's
  whole sentence on lines of their own. They differ from the reference
  host's by those seven changes: the one mark on the loan period, the dot
  and its edge at the graph's top level, the words on the marks, the
  indented line under the renew arm, the `legend`, the start edge's
  caption, and the rules column's `caption` and `explanation_lines`, with
  the sizes they hold the column and its pane at.
  """

  alias StatifierBlocks.{Block, Decode, Document, Palette, ViewModel}

  @documents Path.join([__DIR__, "..", "fixtures", "documents", "statifier_examples_c620756"])
  @graphs Path.join([__DIR__, "..", "fixtures", "map"])
  @keys ["library_loan", "patron_registration"]

  # The reference host's table at the same commit, word for word.
  @phrases %{
    "copy.returned" => "the copy is returned",
    "copy.reported_lost" => "the copy is reported lost",
    "loan.closed" => "the loan is closed",
    "loan.renewed" => "the loan is renewed",
    "loan.overdue" => "the loan is overdue",
    "email.verified" => "the email address is verified",
    "guardian.consented" => "a guardian consents",
    "card.ready" => "the card is ready",
    "patron.asked_to_visit" => "the patron is asked to visit",
    "patron.welcomed" => "the patron is welcomed",
    "registration.abandoned" => "the registration is abandoned",
    "registration.deadline" => "the registration week is up"
  }

  @doc "The two teaching documents' keys, in the order a page offers them."
  @spec keys() :: [String.t()]
  def keys, do: @keys

  @doc "The teaching document `key`, strictly decoded."
  @spec document!(String.t()) :: Document.t()
  def document!(key) when key in @keys do
    {:ok, document} = Decode.decode(File.read!(Path.join(@documents, "#{key}.json")))
    document
  end

  @doc "The view model of the teaching document `key`, under the core palette."
  @spec view_model!(String.t()) :: ViewModel.t()
  def view_model!(key), do: key |> document!() |> ViewModel.build(Palette.core(), [])

  @doc "The checked-in graph for `key`, regenerated from the package's own Map."
  @spec fixture_graph!(String.t()) :: map()
  def fixture_graph!(key) when key in @keys,
    do: JSON.decode!(File.read!(Path.join(@graphs, "#{key}.graph.json")))

  @doc """
  Library loans written here whose abandoning groups sit deeper than the
  root's last step, each as `{key, document, last, abandoning}`: the root's
  last step and the groups in tail position whose rules abandon them, in
  reading order.

  - `"lost_while_overdue"`: the teaching loan with the otherwise arm's
    late-return wait held in a group a loss report abandons, so the group
    is the last step of an arm of the root's last step, a branch;
  - `"overdue_inside_loan"`: a loan group whose renewal rule only resumes
    it, its body ending in an overdue group a loss report abandons;
  - `"lost_at_either_level"`: the same loan with a return rule that
    abandons the loan group too, so two groups abandon into one end.
  """
  @spec deep_abandons() :: [{String.t(), Document.t(), String.t(), [String.t()]}]
  def deep_abandons do
    loan = document!("library_loan")

    lost_while_overdue =
      update_in(loan.root.slots["body"], fn [on_loan, due] ->
        [
          on_loan,
          update_in(due.slots["otherwise"], fn [notice, late] -> [notice, held(late)] end)
        ]
      end)

    [
      {"lost_while_overdue", lost_while_overdue, "blk_ll_due", ["blk_ll_overdue"]},
      {"overdue_inside_loan", nested_loan(["resume"]), "blk_ll_on_loan", ["blk_ll_overdue"]},
      {"lost_at_either_level", nested_loan(["resume", "abandon"]), "blk_ll_on_loan",
       ["blk_ll_on_loan", "blk_ll_overdue"]}
    ]
  end

  # The late return held in a group a loss report abandons.
  defp held(late) do
    Block.new("core.group",
      id: "blk_ll_overdue",
      slots: %{"body" => [late], "interrupts" => [lost("blk_ll_lost_late")]}
    )
  end

  # A loan group whose rules take `outcomes` in turn - a renewal, then a
  # return - its body the loan period and then an overdue group.
  defp nested_loan(outcomes) do
    rules =
      Enum.zip_with(
        [{"blk_ll_renewed_rule", "loan.renewed"}, {"blk_ll_returned_early", "copy.returned"}],
        outcomes,
        fn {id, event}, outcome ->
          Block.new("core.on_event", id: id, config: %{"event" => event, "outcome" => outcome})
        end
      )

    period = Block.new("core.wait", id: "blk_ll_loan_period", config: %{"duration" => "21d"})

    late =
      Block.new("core.await",
        id: "blk_ll_late_return",
        config: %{"event" => "copy.returned", "timeout" => "14d"}
      )

    on_loan =
      Block.new("core.group",
        id: "blk_ll_on_loan",
        slots: %{"body" => [period, held(late)], "interrupts" => rules}
      )

    "core.sequence"
    |> Block.new(id: "blk_ll_root", slots: %{"body" => [on_loan]})
    |> Document.new(id: "bdoc_library_loan", accepts: ["copy.returned", "copy.reported_lost"])
  end

  defp lost(id),
    do:
      Block.new("core.on_event",
        id: id,
        config: %{"event" => "copy.reported_lost", "outcome" => "abandon"}
      )

  @doc "The library world's words for `event`, or `nil`."
  @spec phrase(String.t()) :: String.t() | nil
  def phrase(event) when is_binary(event), do: Map.get(@phrases, event)
end
